#Operations on String
# Concatenation
str1 = "Hello"
str2 = "World"
result = str1 + " " + str2
print(result)
# Repetition
print("Python! " * 3)
# Indexing
text = "Python"
print(text[0])
print(text[-1])
# Slicing
print(text[0:3])
print(text[:4])
print(text[2:])
# Membership
print('Pyt' in text)
print('Java' not in text)

#Builtin String Functions

# 1. len()
text = "Hello World"
print(len(text))
# 2. max() and min()
print(max("abcXYZ"))
print(min("abcXYZ"))
# 3. sorted()
print(sorted("python"))
# 4. chr() and ord()
print(ord('A'))
print(chr(97))
print(ord('a'))
print(chr(66))


